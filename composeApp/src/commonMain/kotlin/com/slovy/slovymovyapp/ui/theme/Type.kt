val MaterialTheme.serifFontFamily: FontFamily
    @Composable get() = typography.displayLarge.fontFamily ?: FontFamily.Serif

/**
 * Italic for localized UI copy, resolved upright where the script has no italic cut.
 *
 * CJK typefaces ship no true italic, so the platform synthesises one by shearing the outlines. That
 * distorts stroke weights and joins, and it is worst at the small sizes this app italicises at.
 * Hierarchy in those locales comes from size, weight and colour instead.
 *
 * Dictionary content uses [FontStyle.Italic] directly rather than this: it is always written in a
 * learning language, and every learning language is Latin or Cyrillic.
 */
val MaterialTheme.uiItalic: FontStyle
    @Composable get() =
        if (Locale.current.language in SCRIPTS_WITHOUT_ITALIC) FontStyle.Normal else FontStyle.Italic

private val SCRIPTS_WITHOUT_ITALIC = setOf("zh", "ja", "ko")

